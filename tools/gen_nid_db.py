#!/usr/bin/env python3
"""Generate src/hle/nid_db.inc: names for every NID the game's modules import.

The full NID -> name table comes from shadPS4 (src/core/aerolib/aerolib.inl,
GPL-2.0-or-later); we keep only the entries Driveclub actually uses.

Usage:
    tools/gen_nid_db.py shadps4/src/core/aerolib/aerolib.inl extracted/Image0 src/hle/nid_db.inc
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from elfinfo import (DT_SCE_STRTAB, DT_SCE_SYMTAB, DT_SCE_SYMTABSZ,  # noqa: E402
                     PT_DYNAMIC, PT_SCE_DYNLIBDATA, Self)

import collections  # noqa: E402
import struct  # noqa: E402


def imported_nids(path):
    with open(path, "rb") as f:
        s = Self(f.read())
    idx, dynlib_ph = s.phdr(PT_SCE_DYNLIBDATA)
    dynlib = s.blobs[idx]
    _, dyn_ph = s.phdr(PT_DYNAMIC)
    start = dyn_ph[2] - dynlib_ph[2]
    dyn = dynlib[start:start + dyn_ph[5]]
    tags = collections.defaultdict(list)
    for off in range(0, len(dyn), 16):
        tag, val = struct.unpack_from("<qQ", dyn, off)
        tags[tag].append(val)
    strtab = tags[DT_SCE_STRTAB][0]
    symtab = tags[DT_SCE_SYMTAB][0]
    nids = set()
    for off in range(0, tags[DT_SCE_SYMTABSZ][0], 24):
        name_off, _, _, shndx, _, _ = struct.unpack_from("<IBBHQQ", dynlib, symtab + off)
        begin = strtab + name_off
        name = dynlib[begin:dynlib.index(b"\0", begin)].decode()
        if shndx == 0 and name.count("#") == 2:
            nids.add(name.split("#")[0])
    return nids


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    aerolib, game_dir, out = sys.argv[1:]

    wanted = set()
    for root in (game_dir, os.path.join(game_dir, "sce_module")):
        for name in sorted(os.listdir(root)):
            if name == "eboot.bin" or name.endswith((".prx", ".sprx")):
                wanted |= imported_nids(os.path.join(root, name))

    stub = re.compile(r'STUB\("([^"]{11})",\s*([^)]+)\)')
    names = {}
    with open(aerolib) as f:
        for line in f:
            m = stub.search(line)
            if m and m.group(1) in wanted:
                names[m.group(1)] = m.group(2).strip()

    with open(out, "w") as f:
        f.write("// Generated by tools/gen_nid_db.py from shadPS4's aerolib.inl\n")
        f.write("// (GPL-2.0-or-later). Do not edit by hand.\n")
        for nid in sorted(names):
            f.write(f'{{"{nid}", "{names[nid]}"}},\n')
    print(f"{len(names)} of {len(wanted)} imported NIDs named -> {out}")


if __name__ == "__main__":
    main()
